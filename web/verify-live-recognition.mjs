 const captured=timeline.find(item=>item.beforeReturn&&item.stream.regions.some(r=>!r.done&&r.raw.replace(/^[# ]+/,'').trim().length>2));
 assert(captured,'需要真实模型返回前采集的正文');
 await page.getByRole('button',{name:'返回首页',exact:true}).click();
