 await page.evaluate(()=>{const region={requestId:'reqr2',type:'table',attempt:2,raw:'最新增量',done:false};window.emit(6,[region]);window.emit(5,[{...region,raw:'乱序旧增量'}]);});
 await page.getByText('最新增量',{exact:true}).waitFor();assert.equal(await page.getByText('乱序旧增量',{exact:true}).count(),0);
 results.push('保留区域 DOM，重试替换正文，表格即时显示，隔离旧作业');
 await page.evaluate(()=>{window.saved.mode='real-ocr';window.saved.blocks=[{id:'b1',type:'text',markdown:'最终保存正文',sourceStatus:'ok'},{id:'b2',type:'table',markdown:'最终保存表格',sourceStatus:'ok'}];window.saved.recognition={...window.saved.recognition,sequence:7,state:'succeeded',message:'已保存',liveOutput:true};window.nativeEvent('recognition',window.saved.recognition);});
 await page.getByText('最终保存正文',{exact:true}).waitFor();
 assert.equal(await page.locator('[data-done="true"]').count(),2);
