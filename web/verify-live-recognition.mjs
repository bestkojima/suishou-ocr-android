 await page.evaluate(()=>window.emit(4,[{requestId:'reqr1',type:'text',attempt:1,raw:'正在生成的中文😀，完成第一段。',done:true},{requestId:'reqr2',type:'table',attempt:2,raw:'修正后的表格',done:false}]));
 await page.getByText('修正后的表格',{exact:true}).waitFor();
