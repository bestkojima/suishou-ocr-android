 await page.getByRole('button',{name:'拍照',exact:true}).click();
 await page.getByText('实际模型流快照',{exact:true}).waitFor();
 await page.evaluate(regions=>window.emit(2,regions),captured.stream.regions);
 const generated=captured.stream.regions.find(r=>!r.done&&r.raw.replace(/^[# ]+/,'').trim().length>2);
 const region=page.locator(`[data-region="live-${generated.requestId}"]`);
 await region.waitFor();assert((await region.textContent()).includes(generated.raw.replace(/^[# ]+/,'').trim()));
